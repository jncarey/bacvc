#!/usr/bin/env bash
#
# 01_build_snpeff_db.sh
#
# Build snpEff databases for each reference genome using:
#   - bakta_gff/<sample>/<sample>.gbff  -> genes.gff (via gbff_to_snpeff_gff.py)
#   - bakta_gff/<sample>/<sample>.fna   -> sequences.fa
#
# The bakta .fna has contig names matching the GFF (contig_1, contig_2, ...),
# unlike the raw fa/ files which use numeric-only names.
#
# Usage:
#   conda activate snippy
#   bash 01_build_snpeff_db.sh [SAMPLE ...]
#   # If no samples given, processes all samples found via *.gbff
#
# Output:
#   snpeff/<sample>/          - snpEff database directory
#   snpeff/snpeff.config      - unified snpEff config for all samples

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
source "${SCRIPT_DIR}/config.sh"

# ---------------------------------------------------------------------------
# Discover samples
# ---------------------------------------------------------------------------
if [[ $# -gt 0 ]]; then
    SAMPLES=("$@")
else
    SAMPLES=()
    for gbff in "${BAKTA_GFF_DIR}"/*/*.gbff; do
        sample="$(basename "$gbff" .gbff)"
        SAMPLES+=("$sample")
    done
fi

if [[ ${#SAMPLES[@]} -eq 0 ]]; then
    echo "ERROR: No .gbff files found in ${BAKTA_GFF_DIR}" >&2
    exit 1
fi

echo "Building snpEff databases for ${#SAMPLES[@]} samples:"
printf '  %s\n' "${SAMPLES[@]}"
echo ""

# ---------------------------------------------------------------------------
# Create unified snpeff.config
# ---------------------------------------------------------------------------
mkdir -p "${SNPEFF_DIR}"

CONFIG="${SNPEFF_DIR}/snpeff.config"
cat > "${CONFIG}" <<'HEADER'
# snpEff configuration for population-specific reference genomes
# Auto-generated by 01_build_snpeff_db.sh

data.dir = .

HEADER

# Codon table (standard bacterial)
cat >> "${CONFIG}" <<'CODON'
codon.Standard : TTT/F, TTC/F, TTA/L, TTG/L+, TCT/S, TCC/S, TCA/S, TCG/S, TAT/Y, TAC/Y, TAA/*, TAG/*, TGT/C, TGC/C, TGA/*, TGG/W, CTT/L, CTC/L, CTA/L, CTG/L+, CCT/P, CCC/P, CCA/P, CCG/P, CAT/H, CAC/H, CAA/Q, CAG/Q, CGT/R, CGC/R, CGA/R, CGG/R, ATT/I, ATC/I, ATA/I, ATG/M+, ACT/T, ACC/T, ACA/T, ACG/T, AAT/N, AAC/N, AAA/K, AAG/K, AGT/S, AGC/S, AGA/R, AGG/R, GTT/V, GTC/V, GTA/V, GTG/V, GCT/A, GCC/A, GCA/A, GCG/A, GAT/D, GAC/D, GAA/E, GAG/E, GGT/G, GGC/G, GGA/G, GGG/G
codon.Bacterial_and_Plant_Plastid : TTT/F, TTC/F, TTA/L, TTG/L+, TCT/S, TCC/S, TCA/S, TCG/S, TAT/Y, TAC/Y, TAA/*, TAG/*, TGT/C, TGC/C, TGA/*, TGG/W, CTT/L, CTC/L, CTA/L, CTG/L+, CCT/P, CCC/P, CCA/P, CCG/P, CAT/H, CAC/H, CAA/Q, CAG/Q, CGT/R, CGC/R, CGA/R, CGG/R, ATT/I+, ATC/I+, ATA/I+, ATG/M+, ACT/T, ACC/T, ACA/T, ACG/T, AAT/N, AAC/N, AAA/K, AAG/K, AGT/S, AGC/S, AGA/R, AGG/R, GTT/V, GTC/V, GTA/V, GTG/V+, GCT/A, GCC/A, GCA/A, GCG/A, GAT/D, GAC/D, GAA/E, GAG/E, GGT/G, GGC/G, GGA/G, GGG/G
CODON

echo "" >> "${CONFIG}"

# ---------------------------------------------------------------------------
# Build database for each sample
# ---------------------------------------------------------------------------
FAIL_COUNT=0

for sample in "${SAMPLES[@]}"; do
    echo "=== ${sample} ==="

    GBFF="${BAKTA_GFF_DIR}/${sample}/${sample}.gbff"
    FNA="${BAKTA_GFF_DIR}/${sample}/${sample}.fna"

    # Validate inputs
    if [[ ! -f "${GBFF}" ]]; then
        echo "  ERROR: GenBank file not found: ${GBFF}" >&2
        FAIL_COUNT=$((FAIL_COUNT + 1))
        continue
    fi
    if [[ ! -f "${FNA}" ]]; then
        echo "  ERROR: FNA not found: ${FNA}" >&2
        FAIL_COUNT=$((FAIL_COUNT + 1))
        continue
    fi

    # Create data directory
    DB_DIR="${SNPEFF_DIR}/${sample}"
    mkdir -p "${DB_DIR}"

    # Convert GenBank to flat snippy-style GFF for snpEff
    python3 "${SCRIPT_DIR}/gbff_to_snpeff_gff.py" "${GBFF}" > "${DB_DIR}/genes.gff"
    echo "  Created genes.gff from GenBank"

    # Copy genome FASTA as sequences.fa (snpEff convention)
    cp "${FNA}" "${DB_DIR}/sequences.fa"
    echo "  Copied FNA -> ${DB_DIR}/sequences.fa"

    # Extract contig names from the generated GFF for config
    CONTIGS=$(grep "^##sequence-region" "${DB_DIR}/genes.gff" | awk '{print $2}')

    # Add genome entry to config
    {
        echo "${sample}.genome : ${sample} Pseudomonas aeruginosa"
        for contig in ${CONTIGS}; do
            echo "  ${sample}.${contig}.codonTable : Bacterial_and_Plant_Plastid"
        done
    } >> "${CONFIG}"

    echo "  Added config entry for ${sample}"

    # Build snpEff database
    echo "  Building snpEff database..."
    if snpEff build \
        -c "${CONFIG}" \
        -dataDir "${SNPEFF_DIR}" \
        -gff3 "${sample}" 2>&1 | tail -5; then
        echo "  SUCCESS: ${sample}"
    else
        echo "  ERROR: snpEff build failed for ${sample}" >&2
        FAIL_COUNT=$((FAIL_COUNT + 1))
    fi

    echo ""
done

echo "========================================="
echo "Done. Built ${#SAMPLES[@]} databases (${FAIL_COUNT} failures)."
echo "Config: ${CONFIG}"
echo "Data:   ${SNPEFF_DIR}/<sample>/"
echo "========================================="

if [[ ${FAIL_COUNT} -gt 0 ]]; then
    exit 1
fi
