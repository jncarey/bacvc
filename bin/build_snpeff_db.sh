#!/usr/bin/env bash
#
# build_snpeff_db.sh
#
# Library entry point for building one reference's snpEff database, with no
# config.sh dependency: every path is an explicit argument. Unlike
# 01_build_snpeff_db.sh (which appends each sample's genome entry to one
# shared results/snpeff/snpeff.config -- safe there only because that script
# runs samples sequentially in one process), this writes a self-contained
# config covering just this one genome, so parallel invocations (e.g. one
# job per reference from an external Snakemake pipeline) never race on a
# shared file, and no aggregation step is needed afterward: the config this
# produces is already everything `snpEff ann`/`snpEff build` need for this
# one reference.
#
# Usage:
#   build_snpeff_db.sh <ref_name> <gbff> <fna> <out_datadir>
#
# Output (under <out_datadir>/<ref_name>/):
#   genes.gff      - flat CDS-only GFF (via gbff_to_snpeff_gff.py)
#   sequences.fa   - copy of <fna>, snpEff's expected filename
#   snpeff.config  - self-contained config for just this one genome
#   snpEffectPredictor.bin, etc. - snpEff's own build artifacts
#
# The built <out_datadir>/<ref_name>/snpeff.config is what you then pass as
# normalize_annotate_vcf.sh's <snpeff_config> and
# 04_generate_variant_tables.py's --gff-derived annotation lookup (see
# README.md's "Building blocks").

set -euo pipefail

if [[ $# -ne 4 ]]; then
    echo "Usage: $0 <ref_name> <gbff> <fna> <out_datadir>" >&2
    exit 1
fi

REF_NAME="$1"
GBFF="$2"
FNA="$3"
OUT_DATADIR="$4"

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"

if [[ ! -f "${GBFF}" ]]; then
    echo "ERROR: GenBank file not found: ${GBFF}" >&2
    exit 1
fi
if [[ ! -f "${FNA}" ]]; then
    echo "ERROR: FNA not found: ${FNA}" >&2
    exit 1
fi

DB_DIR="${OUT_DATADIR}/${REF_NAME}"
mkdir -p "${DB_DIR}"

python3 "${SCRIPT_DIR}/gbff_to_snpeff_gff.py" "${GBFF}" > "${DB_DIR}/genes.gff"
echo "Created ${DB_DIR}/genes.gff from ${GBFF}"

cp "${FNA}" "${DB_DIR}/sequences.fa"
echo "Copied ${FNA} -> ${DB_DIR}/sequences.fa"

CONFIG="${DB_DIR}/snpeff.config"
cat > "${CONFIG}" <<HEADER
# snpEff configuration for ${REF_NAME} (self-contained, one genome only)
# Auto-generated by build_snpeff_db.sh

data.dir = .

HEADER

# Codon table (standard bacterial) -- same definitions as
# 01_build_snpeff_db.sh; static and identical for every reference.
cat >> "${CONFIG}" <<'CODON'
codon.Standard : TTT/F, TTC/F, TTA/L, TTG/L+, TCT/S, TCC/S, TCA/S, TCG/S, TAT/Y, TAC/Y, TAA/*, TAG/*, TGT/C, TGC/C, TGA/*, TGG/W, CTT/L, CTC/L, CTA/L, CTG/L+, CCT/P, CCC/P, CCA/P, CCG/P, CAT/H, CAC/H, CAA/Q, CAG/Q, CGT/R, CGC/R, CGA/R, CGG/R, ATT/I, ATC/I, ATA/I, ATG/M+, ACT/T, ACC/T, ACA/T, ACG/T, AAT/N, AAC/N, AAA/K, AAG/K, AGT/S, AGC/S, AGA/R, AGG/R, GTT/V, GTC/V, GTA/V, GTG/V, GCT/A, GCC/A, GCA/A, GCG/A, GAT/D, GAC/D, GAA/E, GAG/E, GGT/G, GGC/G, GGA/G, GGG/G
codon.Bacterial_and_Plant_Plastid : TTT/F, TTC/F, TTA/L, TTG/L+, TCT/S, TCC/S, TCA/S, TCG/S, TAT/Y, TAC/Y, TAA/*, TAG/*, TGT/C, TGC/C, TGA/*, TGG/W, CTT/L, CTC/L, CTA/L, CTG/L+, CCT/P, CCC/P, CCA/P, CCG/P, CAT/H, CAC/H, CAA/Q, CAG/Q, CGT/R, CGC/R, CGA/R, CGG/R, ATT/I+, ATC/I+, ATA/I+, ATG/M+, ACT/T, ACC/T, ACA/T, ACG/T, AAT/N, AAC/N, AAA/K, AAG/K, AGT/S, AGC/S, AGA/R, AGG/R, GTT/V, GTC/V, GTA/V, GTG/V+, GCT/A, GCC/A, GCA/A, GCG/A, GAT/D, GAC/D, GAA/E, GAG/E, GGT/G, GGC/G, GGA/G, GGG/G
CODON

echo "" >> "${CONFIG}"

CONTIGS=$(grep "^##sequence-region" "${DB_DIR}/genes.gff" | awk '{print $2}')

{
    echo "${REF_NAME}.genome : ${REF_NAME} Pseudomonas aeruginosa"
    for contig in ${CONTIGS}; do
        echo "  ${REF_NAME}.${contig}.codonTable : Bacterial_and_Plant_Plastid"
    done
} >> "${CONFIG}"

echo "Building snpEff database for ${REF_NAME}..."
snpEff build \
    -c "${CONFIG}" \
    -dataDir "${OUT_DATADIR}" \
    -gff3 "${REF_NAME}" 2>&1 | tail -5

echo "Built: ${DB_DIR} (config: ${CONFIG})"
